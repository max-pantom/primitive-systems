const detail = (d: ComponentDef) => ({
  id: d.id,
  name: d.name,
  description: d.description,
  tags: d.tags,
  status: d.status,
  usage: d.usage,
  guidelines: d.guidelines ?? null,
  since: d.since,
  mark: d.mark ?? null,
  composition: d.composition ?? null,
  props: d.props.map((p) => ({ name: p.name, type: p.type, default: p.default, description: p.description, control: p.control })),
  defaults: defaultsOf(d.props),
  a11y: (({ contrast, keyboard, labels }) => ({ contrast, keyboard, labels }))(a11yReport(d, d.render(defaultsOf(d.props)))),
  frameworks: [...FRAMEWORKS],
});

export function listTemplates() {
  return { templates: templates.map(({ id, name, description, tags, uses, since, mark }) => ({ id, name, description, tags, uses: uses ?? [], since, mark: mark ?? null })) };
}

/** A whole screen: its props, guidelines and, when a framework is given, ready-to-paste code. */
export function getTemplateBrief(id: string, framework?: string, props?: Record<string, unknown>) {
  const t = getTemplate(id);
  if (!t) throw new ApiError(404, `Unknown template: ${id}`);
  return { id: t.id, name: t.name, uses: t.uses ?? [], props: briefProps(t), code: getCodeBrief({ component: id, framework: framework ?? 'p8', props: props ?? {} }).code };
}

export function getTemplateDetail(id: string, framework?: string, props?: Record<string, unknown>) {
  const t = getTemplate(id);
  if (!t) throw new ApiError(404, `Unknown template: ${id}`);
  const base = { ...detail(t), uses: t.uses ?? [] };
  if (!framework) return base;
  const code = getCode({ component: id, framework, props: props ?? {} });
  return { ...base, code };
}

const vErr = <T,>(fn: () => T): T => { try { return fn(); } catch (e) { if (e instanceof VersionError) throw new ApiError(400, e.message); throw e; } };
const isCurrent = (v?: string) => !v || v === LATEST || v === RELEASES[0].version;

const briefProps = (d: ComponentDef) => d.props.map((p) => ({ name: p.name, type: p.type, default: p.default, ...(p.control.kind === 'select' ? { options: p.control.options } : {}) }));
const snippet = (id: string) => generate(getDef(id)!, {}, 'p8').code.trim();

/** Short form for agents low on context: props and the snippet, nothing else. */
export function getComponentBrief(id: string) {
  const def = getDef(id);
  if (!def) throw new ApiError(404, `Unknown component: ${id}`);
  return { id: def.id, name: def.name, description: def.description, props: briefProps(def), snippet: snippet(def.id) };
}

export function getComponent(id: string, version?: string) {
  const def = getDef(id);
  if (!isCurrent(version)) {
    const pinned = vErr(() => pinnedProps(id, version!));
    const d = vErr(() => diffComponent(id, version!));
    return {
      id, name: pinned.name, version: pinned.version, pinned: true, current: RELEASES[0].version,
      props: pinned.props, note: `Props as they were in ${pinned.version}. Code is always generated by the current engine; use diff_component to see what changed and how to migrate.`,
      sinceThen: { status: d.status, breaking: d.breaking, migration: d.migration },
    };
  }
  if (!def) throw new ApiError(404, `Unknown component: ${id}`);
  return detail(def);
}

export const listVersions = () => ({ ...versionList(), releases: RELEASES.map((r) => ({ version: r.version, title: r.title })) });

/** What changed in one component (id) or in the whole library (no id) between two releases, with migration hints. */
export function getDiff(input: { id?: string; from?: string; to?: string }) {
  if (!input.from) throw new ApiError(400, 'from: a version is required (see list_versions)');
  return vErr(() => (input.id ? diffComponent(input.id, input.from!, input.to ?? LATEST) : diffAll(input.from!, input.to ?? LATEST)));
}

export const getTokens = () => flatTokens();

/** Only the code: for agents low on context. */
export function getCodeBrief(input: unknown) {
  const r = getCode(input);
  return { framework: r.framework, code: r.code };
}

const zodMessage = (e: z.ZodError) => e.issues.map((i) => (i.code === 'unrecognized_keys' ? `unknown prop(s): ${(i as unknown as { keys: string[] }).keys.join(', ')}` : `props.${i.path.join('.')}: ${i.message}`)).join('; ');

const codeInput = z.object({
  component: z.string(),
  framework: z.enum(FRAMEWORKS),
  props: z.record(z.string(), z.unknown()).optional(),
  version: z.string().optional(),
});

export function getCode(input: unknown) {
  const parsed = codeInput.safeParse(input);
  if (!parsed.success) throw new ApiError(400, parsed.error.issues.map((i) => `${i.path.join('.') || 'input'}: ${i.message}`).join('; '));
  const def = getDef(parsed.data.component);
  if (!def) throw new ApiError(404, `Unknown component: ${parsed.data.component}`);
  const { version } = parsed.data;
  try {
    if (!isCurrent(version)) {
      const errs = vErr(() => validatePinned(def.id, version!, parsed.data.props ?? {}));
      if (errs.length) throw new ApiError(400, `Props do not match ${version}: ${errs.join('; ')}`);
      const d = vErr(() => diffComponent(def.id, version!));
      const out = generate(def, parsed.data.props ?? {}, parsed.data.framework);
      return { ...out, pin: { requested: d.from, current: RELEASES[0].version, status: d.status, outputChanged: d.style === 'changed' || d.markup === 'changed', breaking: d.breaking, migration: d.migration, note: 'Old generated code is not archived: this code comes from the current engine. If outputChanged is true, replace anything you pasted earlier with this.' } };
    }
    return generate(def, parsed.data.props ?? {}, parsed.data.framework);
  } catch (e) {
    if (e instanceof z.ZodError) throw new ApiError(400, zodMessage(e));
    throw e;
  }
}

export const getRules = () => ({ voice: VOICE, rules: RULES, exceptions: EXCEPTIONS, grid: { space: GRID_SPACE, radius: RADII, gaps: GAPS }, guidelines: Object.fromEntries(components.map((c) => [c.id, c.guidelines])) });

const composeInput = z.object({
  framework: z.enum(FRAMEWORKS),
  direction: z.enum(['column', 'row']).default('column'),
  gap: z.enum(['4', '8', '12']).default('12'),
  items: z.array(z.object({ component: z.string(), props: z.record(z.string(), z.unknown()).optional() })).min(1).max(30),
});

/** Several component instances composed into one ready-to-paste output (a Stack of them). */
export function composeCode(input: unknown) {
  const parsed = composeInput.safeParse(input);
  if (!parsed.success) throw new ApiError(400, parsed.error.issues.map((i) => `${i.path.join('.') || 'input'}: ${i.message}`).join('; '));
  const { framework, direction, gap, items } = parsed.data;
  const nodes: Node[] = [];
  const p8: string[] = [];
  for (const it of items) {
    const def = getDef(it.component);
    if (!def) throw new ApiError(404, `Unknown component: ${it.component}`);
    try {
      const props = parseProps(def, it.props ?? {});
      nodes.push(def.render(props));
      if (framework === 'p8') p8.push(generate(def, props, 'p8').code.trim());
    } catch (e) {
      if (e instanceof z.ZodError) throw new ApiError(400, `${it.component}: ${zodMessage(e)}`);
      throw e;
    }
  }
  const stackCls = ['p8-stack', `p8-stack--gap${gap}`, 'p8-stack--align-stretch', ...(direction === 'row' ? ['p8-stack--row'] : [])];
  if (framework === 'p8') return { component: 'composition', framework, language: 'html', filename: 'composition.p8.html', props: {}, code: `<div style="display:flex;flex-direction:${direction};gap:var(--p8-space-${gap})">\n${p8.map((l) => `  ${l}`).join('\n')}\n</div>\n` };
  const root: Node = { tag: 'div', cls: stackCls, children: nodes };
  const synthetic: ComponentDef = { id: 'composition', name: 'Composition', description: '', tags: [], status: 'stable', usage: '', props: [], rules: [], render: () => root };
  return generate(synthetic, {}, framework);
}

export function getThemeBuild(input: unknown) {
  const r = buildTheme((input ?? {}) as Parameters<typeof buildTheme>[0]);
  if (!r.ok) throw new ApiError(400, r.errors.join('; '));
  return r;
}

export function lintCode(input: unknown) {
  const { code, fix } = (input ?? {}) as { code?: unknown; fix?: unknown };
  if (typeof code !== 'string') throw new ApiError(400, 'code: expected a string');
  if (fix === true) {
    const r = fixCode(code);
    return { ok: r.remaining.every((i) => i.severity !== 'error'), fixed: r.fixed, fixes: r.fixes, issues: r.remaining };
  }
  const issues = lintAll(code);
  return { ok: issues.every((i) => i.severity !== 'error'), issues };
}

