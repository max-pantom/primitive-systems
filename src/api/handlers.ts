const zodMessage = (e: z.ZodError) => e.issues.map((i) => (i.code === 'unrecognized_keys' ? `unknown prop(s): ${(i as unknown as { keys: string[] }).keys.join(', ')}` : `props.${i.path.join('.')}: ${i.message}`)).join('; ');

const codeInput = z.object({
  component: z.string(),
  framework: z.enum(FRAMEWORKS),
  props: z.record(z.string(), z.unknown()).optional(),
  version: z.string().optional(),
});

export function getCode(input: unknown) {
  const parsed = codeInput.safeParse(input);
  if (!parsed.success) throw new ApiError(400, parsed.error.issues.map((i) => `${i.path.join('.') || 'input'}: ${i.message}`).join('; '));
  const def = getDef(parsed.data.component);
  if (!def) throw new ApiError(404, `Unknown component: ${parsed.data.component}`);
  const { version } = parsed.data;
  try {
    if (!isCurrent(version)) {
      const errs = vErr(() => validatePinned(def.id, version!, parsed.data.props ?? {}));
      if (errs.length) throw new ApiError(400, `Props do not match ${version}: ${errs.join('; ')}`);
      const d = vErr(() => diffComponent(def.id, version!));
      const out = generate(def, parsed.data.props ?? {}, parsed.data.framework);
      return { ...out, pin: { requested: d.from, current: RELEASES[0].version, status: d.status, outputChanged: d.style === 'changed' || d.markup === 'changed', breaking: d.breaking, migration: d.migration, note: 'Old generated code is not archived: this code comes from the current engine. If outputChanged is true, replace anything you pasted earlier with this.' } };
    }
    return generate(def, parsed.data.props ?? {}, parsed.data.framework);
  } catch (e) {
    if (e instanceof z.ZodError) throw new ApiError(400, zodMessage(e));
    throw e;
  }
}

