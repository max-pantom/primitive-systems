/** A whole screen: its props, guidelines and, when a framework is given, ready-to-paste code. */
export function getTemplateDetail(id: string, framework?: string, props?: Record<string, unknown>) {
  const t = getTemplate(id);
  if (!t) throw new ApiError(404, `Unknown template: ${id}`);
  const base = { ...detail(t), uses: t.uses ?? [] };
  if (!framework) return base;
  const code = getCode({ component: id, framework, props: props ?? {} });
  return { ...base, code };
}

const vErr = <T,>(fn: () => T): T => { try { return fn(); } catch (e) { if (e instanceof VersionError) throw new ApiError(400, e.message); throw e; } };
const isCurrent = (v?: string) => !v || v === LATEST || v === RELEASES[0].version;

export function getComponent(id: string, version?: string) {
  const def = getDef(id);
  if (!isCurrent(version)) {
    const pinned = vErr(() => pinnedProps(id, version!));
    const d = vErr(() => diffComponent(id, version!));
    return {
      id, name: pinned.name, version: pinned.version, pinned: true, current: RELEASES[0].version,
      props: pinned.props, note: `Props as they were in ${pinned.version}. Code is always generated by the current engine; use diff_component to see what changed and how to migrate.`,
      sinceThen: { status: d.status, breaking: d.breaking, migration: d.migration },
    };
  }
  if (!def) throw new ApiError(404, `Unknown component: ${id}`);
  return detail(def);
}

export const listVersions = () => ({ ...versionList(), releases: RELEASES.map((r) => ({ version: r.version, title: r.title })) });

/** What changed in one component (id) or in the whole library (no id) between two releases, with migration hints. */
export function getDiff(input: { id?: string; from?: string; to?: string }) {
  if (!input.from) throw new ApiError(400, 'from: a version is required (see list_versions)');
  return vErr(() => (input.id ? diffComponent(input.id, input.from!, input.to ?? LATEST) : diffAll(input.from!, input.to ?? LATEST)));
}

